def apply_localization_card_revisions(cards: list[dict]) -> None:
    by_id = {card["id"]: card for card in cards}
    if set(CARD_REVISIONS) - set(by_id):
        raise ValueError("localization-pass Chapter 4 revisions reference missing cards")
    if set(REVIEW_RECORD_REVISIONS_3) != set(CARD_REVISIONS):
        raise ValueError(
            "localization-pass seal set does not match the revised card set"
        )
    for card_id, revision in CARD_REVISIONS.items():
        card = by_id[card_id]
        if "question" in revision:
            card["question"] = revision["question"]
        if "options" in revision:
            card["options"] = list(revision["options"])
        if "explanation" in revision:
            card["explanation"] = revision["explanation"]
        review_record_id, _digest = REVIEW_RECORD_REVISIONS_3[card_id]
        card["review_record_id"] = review_record_id


