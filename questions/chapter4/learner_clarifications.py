def apply_learner_clarifications(card: dict) -> dict:
    """Replace authoring-side wording, keeping the reviewed claim intact."""

    card_id = str(card["id"])
    question = QUESTION_CLARIFICATIONS.get(card_id)
    if question is not None:
        card["question"] = question
    explanation = EXPLANATION_CLARIFICATIONS.get(card_id)
    if explanation is not None:
        card["explanation"] = explanation
    return card


