def apply_option_order(card: dict) -> dict:
    """Rotate the options so the keyed answer lands in its balanced slot."""

    slot = OPTION_ORDER_SLOT.get(str(card["id"]))
    if slot is None:
        return card
    options = list(card["options"])
    correct = card["correct"]
    size = len(options)
    if size < 2 or not isinstance(correct, int) or not 0 <= correct < size:
        raise ValueError(f"cannot balance option order for {card['id']!r}")
    if not 0 <= slot < size:
        raise ValueError(f"target slot {slot} outside option set for {card['id']!r}")
    delta = (correct - slot) % size
    card["options"] = [options[(index + delta) % size] for index in range(size)]
    card["correct"] = slot
    return card


