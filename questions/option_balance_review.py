class OptionBalanceError(RuntimeError):
    """Raised when a balance override would touch the correct option."""


def apply_option_balance(question: dict) -> dict:
    """Replace the listed distractors of one question with balanced wording.

    The question is mutated in place and returned, mirroring the other
    canonical passes. The correct option, question stem, explanation, verse and
    every metadata field are left exactly as reviewed.
    """
    overrides = BALANCED_OPTIONS.get(question.get("id"))
    if not overrides:
        return question

    options = list(question.get("options", ()))
    correct = question.get("correct")
    for index, text in overrides.items():
        if index == correct:
            raise OptionBalanceError(
                f"{question.get('id')}: override names the correct option {index}"
            )
        if not 0 <= index < len(options):
            raise OptionBalanceError(
                f"{question.get('id')}: override index {index} outside options"
            )
        options[index] = text
    question["options"] = options
    return question
